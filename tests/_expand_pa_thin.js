const NEW = { origin: ORIGIN, workflow: WORKFLOW, tools: TOOLS, pitfalls: PITFALLS };

/* ---------- 执行 ---------- */
let src = fs.readFileSync(path, 'utf8');

function jsq(s) {
  return "'" + s
    .replace(/\\/g, '\\\\')
    .replace(/\n/g, '\\n')
    .replace(/'/g, "\\'") + "'";
}

const paIdx = src.indexOf("    id: 'price-action',");
if (paIdx < 0) { console.error('找不到 price-action'); process.exit(1); }
const bStart = src.indexOf('    body: [', paIdx);
const bEnd = src.indexOf("    ].join(''),", bStart);
if (bStart < 0 || bEnd < 0) { console.error('body 定位失败'); process.exit(1); }

const arrText = src.slice(bStart + '    body: '.length, bEnd + 5);   /* "[ ... ]"（含收尾的 ]） */
const arr = eval(arrText);
const origBody = arr.join('');

/* 找各章 h2 元素，替换其后的正文元素 */
const idx = {};
for (let i = 0; i < arr.length; i++) {
  const m = arr[i].match(/<h2 id="([^"]+)">/);
  if (m && NEW[m[1]]) idx[m[1]] = i + 1;   /* 正文元素 = h2 元素的下一个 */
}
console.log('定位到的章：', JSON.stringify(idx));
for (const k of Object.keys(NEW)) {
  if (idx[k] === undefined) { console.error('未定位到章 ' + k); process.exit(1); }
}

const replaced = arr.slice();
for (const k of Object.keys(NEW)) replaced[idx[k]] = NEW[k];
const newBody = replaced.join('');

/* ---------- 重组数组源码（每元素一行），并自验证 ---------- */
function emit(a) {
  let o = '    body: [\n';
  a.forEach(s => { o += '      ' + jsq(s) + ',\n'; });
  o += "    ].join(''),";
  return o;
}

/* 自验证：不改动时重组的 join 必须 == 原 body */
const checkText = emit(arr);
const checkArr = eval(checkText.replace(/^\s*body: /, '').replace(/\]\.join\(''\),?$/, ']'));
if (checkArr.join('') !== origBody) {
  console.error('自验证失败：重组改变了 body，放弃写入');
  process.exit(1);
}

